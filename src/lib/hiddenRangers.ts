export const HIDDEN_RANGERS = new Set<string>([
  'u1651e-al',
  'u1651h-al',
  'u1651u-al',
  'u1652e-al',
])

/** ชื่อโฟลเดอร์/รหัสเรนเจอร์ (หรือพาธที่ขึ้นต้นด้วยมัน) อยู่ในรายการซ่อน */
export const isHiddenRanger = (nameOrPath: string) => HIDDEN_RANGERS.has(nameOrPath.split('/')[0].toLowerCase())
